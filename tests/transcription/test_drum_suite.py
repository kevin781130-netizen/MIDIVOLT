"""Rights-gated multi-song drum suite: tests use synthetic fixtures ONLY."""
from __future__ import annotations

import hashlib
import json
import tempfile
import unittest
from pathlib import Path

import pretty_midi

from midivolt.drum_suite import GM_FAMILIES, run_suite, validate_dataset
from test_drums import PATTERN, PITCH, synthetic_drums


def hash_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def make_sample(folder: Path, index: int) -> dict:
    name = f"synthetic_song_{index}"
    wav = folder / (name + ".wav")
    ref = folder / (name + ".mid")
    synthetic_drums(wav)
    midi = pretty_midi.PrettyMIDI(initial_tempo=138)
    drums = pretty_midi.Instrument(program=0, is_drum=True)
    for instrument, start in PATTERN:
        drums.notes.append(pretty_midi.Note(
            pitch=PITCH[instrument], start=start, end=start + 0.1, velocity=100,
        ))
    midi.instruments.append(drums)
    midi.write(str(ref))
    return {
        "sample_id": name,
        "source_song_id": name,
        "performance_id": f"synthetic_performance_{index}",
        "split": "test",
        "audio_domain": "synthetic_rendered",
        "audio_path": wav.name,
        "reference_midi_path": ref.name,
        "audio_sha256": hash_file(wav),
        "midi_sha256": hash_file(ref),
        "provenance_url": "https://example.org/synthetic-test-fixture",
        "technique_tags": ["simple_groove", "simultaneous_hits"],
        "rights": {
            "status": "approved",
            "commercial_benchmark_allowed": True,
            "audio_license": "test_fixture_owned",
            "midi_license": "test_fixture_owned",
            "evidence_url": "https://example.org/synthetic-test-fixture",
            "reviewer": "MIDIVOLT synthetic test only",
            "attribution": "Generated by MIDIVOLT unit tests, not human performances",
        },
    }


def manifest(folder: Path, samples: list) -> Path:
    file = folder / "dataset.json"
    file.write_text(json.dumps({"schema_version": "1", "samples": samples}), encoding="utf-8")
    return file


class DrumSuiteTests(unittest.TestCase):
    def test_missing_real_recordings_cannot_produce_a_fake_report(self):
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            file = manifest(root, [])
            with self.assertRaisesRegex(ValueError, "No test samples provided"):
                run_suite(file, output_dir=root / "out")
            self.assertFalse((root / "out" / "drum_suite_report.json").exists())

    def test_synthetic_requires_explicit_opt_in(self):
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            file = manifest(root, [make_sample(root, 1)])
            with self.assertRaisesRegex(ValueError, "Synthetic examples require"):
                validate_dataset(file)

    def test_real_and_synthetic_are_never_blended(self):
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            dataset = manifest(root, [make_sample(root, 1), make_sample(root, 2)])
            def fake_adt(wav):
                reference = pretty_midi.PrettyMIDI(str(wav.with_suffix(".mid")))
                return reference, {"engine": "mock_model", "warning": "No real ADT weights loaded"}
            report = run_suite(dataset, output_dir=root / "out", include_synthetic=True,
                               research_only=True, engines=("dsp", "adt_str"),
                               adt_predict=fake_adt)
            self.assertFalse(report["real_recordings_present"])
            self.assertEqual(report["by_audio_domain"]["real_recording"]["dsp"]["sample_count"], 0)
            self.assertEqual(report["by_audio_domain"]["real_recording"]["adt_str"]["song_count"], 0)
            self.assertEqual(report["by_audio_domain"]["synthetic_rendered"]["dsp"]["song_count"], 2)
            self.assertEqual(report["by_audio_domain"]["synthetic_rendered"]["adt_str"]["song_macro_f1"], 1.0)
            self.assertEqual(len(report["samples"]), 4)
            self.assertIn("38", report["by_audio_domain"]["synthetic_rendered"]["dsp"]["per_pitch"])
            self.assertEqual(report["by_audio_domain"]["synthetic_rendered"]["dsp"]["gm_family_coverage"]["ride"], [])
            self.assertTrue((root / "out" / "drum_suite_report.json").exists())

    def test_unapproved_rights_block_before_model_is_run(self):
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            sample = make_sample(root, 1)
            sample["rights"]["status"] = "pending"
            file = manifest(root, [sample])
            calls = []
            def spy(_):
                calls.append(True)
                raise AssertionError("Must never infer with uncleared input")
            with self.assertRaisesRegex(ValueError, "missing approved"):
                run_suite(file, output_dir=root / "out", include_synthetic=True, dsp_predict=spy)
            self.assertEqual(calls, [])

    def test_bad_audio_checksum_blocks_before_output_creation(self):
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            sample = make_sample(root, 1)
            sample["audio_sha256"] = "a" * 64
            file = manifest(root, [sample])
            with self.assertRaisesRegex(ValueError, "SHA-256 mismatch"):
                run_suite(file, output_dir=root / "out", include_synthetic=True)
            self.assertFalse((root / "out").exists())

    def test_missing_separate_midi_permission_rejected(self):
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            sample = make_sample(root, 1)
            del sample["rights"]["midi_license"]
            with self.assertRaisesRegex(ValueError, "rights.midi_license"):
                validate_dataset(manifest(root, [sample]), include_synthetic=True)

    def test_dataset_path_traversal_rejected(self):
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            sample = make_sample(root, 1)
            sample["audio_path"] = "../outside.wav"
            with self.assertRaisesRegex(ValueError, "escape"):
                validate_dataset(manifest(root, [sample]), include_synthetic=True)

    def test_duplicate_sample_id_rejected(self):
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            sample = make_sample(root, 1)
            with self.assertRaisesRegex(ValueError, "Duplicate sample_id"):
                validate_dataset(manifest(root, [sample, sample]), include_synthetic=True)

    def test_adt_requires_research_opt_in(self):
        with tempfile.TemporaryDirectory() as t:
            root = Path(t)
            file = manifest(root, [make_sample(root, 1)])
            with self.assertRaisesRegex(PermissionError, "research-only"):
                run_suite(file, output_dir=root / "out", engines=("adt_str",), include_synthetic=True)

    def test_song_macro_does_not_equal_long_song_event_micro(self):
        # First song 1 TP; second song 1 TP, 3 FP; macro = (1 + .4)/2 = .7.
        from midivolt.drum_suite import _summarize
        def scores(tp, fp, fn):
            return {
                "song_id": None, "seconds": 1.0, "realtime_factor": 0.5,
                "scores": {"micro": {"tp": tp, "fp": fp, "fn": fn},
                           "per_gm_pitch": {"36": {"tp": tp, "fp": fp, "fn": fn}}},
            }
        a = scores(1, 0, 0)
        a["song_id"] = "song_a"
        b = scores(1, 3, 0)
        b["song_id"] = "song_b"
        result = _summarize([a, b])
        self.assertAlmostEqual(result["song_macro_f1"], 0.7)
        self.assertAlmostEqual(result["event_micro"]["f1"], 4/7, places=6)
        self.assertEqual(result["gm_family_coverage"]["kick"], [36])

    def test_families_cover_required_drum_types_without_relabeling_pitches(self):
        for family in ("kick", "snare", "hi_hat", "tom", "ride", "crash"):
            self.assertIn(family, GM_FAMILIES)
            self.assertGreater(len(GM_FAMILIES[family]), 0)


if __name__ == "__main__":
    unittest.main()
